#!/bin/zsh
# Regenerates spirv.h (the Vulkan shaders of stress3d.c as SPIR-V arrays) with glslangValidator.
cd ${0:A:h} || exit 1
glslangValidator -V --vn stress_vert_spv -o vert.h stress.vert && glslangValidator -V --vn stress_frag_spv -o frag.h stress.frag || exit 1
{ print "/* generated by make-shaders.sh from stress.vert and stress.frag, do not edit */"; cat vert.h frag.h; } > spirv.h
rm -f vert.h frag.h
